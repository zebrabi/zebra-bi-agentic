"use strict";
/**
 * Zebra BI report-authoring MCP server.
 *
 * Reads an unopened PBIP project and reports what is wrong with it. The rules come from
 * rules.json, which is generated from the same marked source as the public skill, so a rule's
 * wording cannot drift from the prose a customer reads.
 *
 * Three things about the response shape, each of which exists because of a specific failure:
 *
 *   1. `checked` is reported alongside `findings`. The PowerShell checker this replaces prints
 *      "PRE-FLIGHT: PASS" on an empty directory, because every layer of it is guarded by an
 *      `if` with no else. "Nothing was wrong" and "nothing was looked at" must not be the same
 *      answer.
 *   2. `notChecked` is always non-empty. Most of what breaks a Zebra report is invisible to a
 *      file reader: whether the numbers are right, whether the variance is comparable, whether
 *      the actuals cover the same window. A validator that stays quiet about its own blind
 *      spots converts a caught error into a confident one.
 *   3. There is a real exit path. The script had no exit code at all, so a caller had to parse
 *      text to find out whether anything failed.
 *
 * Zero dependencies. The MCP stdio transport is newline-delimited JSON-RPC 2.0, which is small
 * enough that adding an SDK would mean shipping node_modules inside a plugin to save very
 * little. It also never touches the network, and never writes to the customer's project.
 */


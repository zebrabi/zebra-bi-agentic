const RULES_PATH = path.join(
  __dirname, "..", "skills", "report-authoring", "rules.json"
);

function loadRules() {
  try {
    const raw = JSON.parse(fs.readFileSync(RULES_PATH, "utf8"));
    return Array.isArray(raw.rules) ? raw.rules : [];
  } catch (err) {
    // A missing catalogue is a broken install, not a clean report. Say so rather than
    // returning zero findings, which would read as a pass.
    return null;
  }
}


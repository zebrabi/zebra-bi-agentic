function readJson(abs, rel) {
  const buf = fs.readFileSync(abs);
  const hadBom = buf.length >= 3 && buf[0] === 0xef && buf[1] === 0xbb && buf[2] === 0xbf;
  const text = buf.toString("utf8").replace(/^\uFEFF/, "");
  let parsed = null, parseError = null;
  try { parsed = JSON.parse(text); } catch (e) { parseError = e.message; }
  return { abs, rel, text, parsed, parseError, hadBom };
}

function walk(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    // A symlink to a FILE is not a file in this project. Directory symlinks were already skipped
    // deliberately, but `e.isDirectory()` is false for a symlinked file, so one placed inside the
    // tree was read from wherever it pointed. Same guard as tmdl.js. Corrected 2026-08-31.
    if (e.isSymbolicLink()) continue;
    if (e.isDirectory()) walk(p, out); else out.push(p);
  }
  return out;
}

function resolveProject(projectPath) {
  const p = {
    files: new Map(), checked: [], problems: [], allFiles: [], visuals: [], pages: [],
    pbipFiles: [], pbirFiles: [], declaredPages: [], notCheckedExtra: [],
  };
  if (!projectPath || !fs.existsSync(projectPath)) {
    return { ...p, fatal: `No such directory: ${projectPath}` };
  }
  p.fatal = null;

  const entries = fs.readdirSync(projectPath, { withFileTypes: true });
  const pbip = entries.filter((e) => e.isFile() && e.name.endsWith(".pbip"));
  const reportDirs = entries.filter((e) => e.isDirectory() && e.name.endsWith(".Report"));
  const modelDirs = entries.filter((e) => e.isDirectory() && e.name.endsWith(".SemanticModel"));

  // Report every layer, including duplicates. The checker being replaced silently inspected
  // only the first .Report and .SemanticModel, so a multi-report project said nothing about it.
  p.checked.push(`${pbip.length} .pbip file(s)`);
  p.checked.push(`${reportDirs.length} .Report director(y|ies)`);
  p.checked.push(`${modelDirs.length} .SemanticModel director(y|ies)`);
  if (reportDirs.length > 1 || modelDirs.length > 1) {
    p.problems.push({
      code: "multiple-projects-in-one-directory", severity: "wont-open", location: projectPath,
      message: "This directory holds more than one report or model. Every check below ran "
             + "against the first of each, so the others were not inspected.",
    });
  }

  // ADDED 2026-08-05. With no .Report there is nothing for any report rule to read, and every
  // one of them returns no findings for that reason alone. Reporting `ok: true` there is the
  // instrument claiming success for having read nothing -- which is the same failure this file's
  // header calls out in the PowerShell it replaces, one level up: not "every layer optional" but
  // "no layer at all". It cost a real half-hour: a corpus harness staged 20 projects with directory
  // junctions, a junction answers isSymbolicLink() rather than isDirectory(), and the run
  // reported a clean 0 findings on all 20 templates. `checked` said `0 .Report` and nobody read
  // it, because `ok` said pass. So the honesty has to live in `ok`, not only in the counts.
  if (reportDirs.length === 0) {
    return { ...p, fatal:
        `No *.Report directory in ${projectPath}, so nothing was checked. Every report rule `
      + `needs one and would report no findings for that reason alone. If the path is right, `
      + `check it is not a symlink or a Windows directory junction: those are not directories `
      + `to this resolver and read as absent.` };
  }

  for (const f of pbip) {
    p.pbipFiles.push(readJson(path.join(projectPath, f.name), f.name));
  }

  if (reportDirs.length) {
    const base = path.join(projectPath, reportDirs[0].name);
    for (const abs of walk(base)) {
      if (!/\.(json|pbir)$/i.test(abs)) continue;
      const rel = path.relative(base, abs).split(path.sep).join("/");
      const f = readJson(abs, rel);
      p.allFiles.push(f);
      p.files.set(rel, f);
      if (f.parseError) {
        p.problems.push({
          code: "unparseable-json", severity: "wont-open", location: rel,
          message: `This file is not valid JSON, so Power BI Desktop will refuse the whole `
                 + `project. ${f.parseError}`,
        });
        continue;
      }
      if (rel.endsWith("definition.pbir")) {
        const byPath = f.parsed?.datasetReference?.byPath?.path;
        p.pbirFiles.push({
          ...f, byPath,
          byPathResolves: byPath ? fs.existsSync(path.resolve(base, byPath)) : true,
        });
        // Desktop validates the $schema URL against a PATTERN and refuses the whole project on a
        // mismatch -- "Expected '$schema' property ... to follow patterns" -- before it reads a
        // single page. A plausible URL with one extra path segment
        // (`.../report/definition/definitionProperties/...`) did exactly that on 2026-09-06 while
        // this validator said ok. Project-shape fact, same class as unparseable-json.
        // Only a PRESENT, non-matching value is a measured fault; an absent $schema has not been
        // put through a cold open and is not claimed here.
        const schemaUrl = f.parsed?.$schema;
        const PBIR_SCHEMA = /^https:\/\/developer\.microsoft\.com\/json-schemas\/fabric\/item\/report\/definitionProperties\/[12]\.\d+\.\d+\/schema\.json$/;
        if (typeof schemaUrl === "string" && !PBIR_SCHEMA.test(schemaUrl)) {
          p.problems.push({
            code: "pbir-schema-url-invalid", severity: "wont-open", location: rel,
            message: `definition.pbir's $schema is '${schemaUrl}', `
              + "and Power BI Desktop checks it against a pattern before it opens anything: it must be "
              + "https://developer.microsoft.com/json-schemas/fabric/item/report/definitionProperties/2.0.0/schema.json "
              + "(a 1.x.y or 2.x.y version). Anything else refuses the whole project with "
              + "\"Expected '$schema' property ... to follow patterns\".",
          });
        }
      } else if (/^definition\/pages\/[^/]+\/page\.json$/.test(rel)) {
        p.pages.push({ ...f, pageName: rel.split("/")[2] });
      } else if (/\/visuals\/[^/]+\/visual\.json$/.test(rel)) {
        p.visuals.push({
          ...f,
          name: f.parsed?.name ?? rel.split("/").slice(-2)[0],
          visualType: f.parsed?.visual?.visualType ?? "",
        });
      }
    }
    const pages = p.files.get("definition/pages/pages.json");
    if (pages && !pages.parseError) p.declaredPages = pages.parsed?.pageOrder ?? [];
    p.checked.push(`${p.pages.length} page(s)`, `${p.visuals.length} visual(s)`,
                   `${p.allFiles.length} report file(s) parsed`);

    // A report can legitimately have no visuals yet, so this is not a fault and not fatal. But
    // most of the catalogue reads visuals, so a green result here means far less than a green
    // result on a populated report, and the caller must not have to work that out from a count.
    if (p.visuals.length === 0) {
      p.notCheckedExtra.push("Anything about a visual: this report has none, so most of the "
        + "catalogue had nothing to read and stayed silent for that reason rather than because "
        + "your visuals are correct.");
    }
  }

  // The model layer. Everything above reads the report; these are the only facts that come
  // from the semantic model, and they are the two the plan calls commercially decisive.
  p.model = tmdl.readModel(projectPath);
  if (p.model.present && p.model.tables.length === 0) {
    // A model directory with nothing parsed out of it is not a model with no measures. Saying
    // "this has no scenario measures" here would be inferring absence from absence of evidence,
    // which is the one thing this tool is built not to do.
    p.checked.push(`${p.model.files.length} TMDL file(s), 0 tables parsed`);
    p.notCheckedExtra.push("The semantic model: no TMDL tables could be read, so nothing is "
      + "claimed about scenario measures or a marked date table.");
  } else if (p.model.present) {
    p.checked.push(`${p.model.files.length} TMDL file(s)`, `${p.model.tables.length} table(s)`);

    // Reported, never flagged. All 20 shipped templates sit at 1600 or 1601 and every one of
    // them opens, so a finding here would warn on correct reports. It matters for exactly one
    // thing: Desktop upgrades the model in memory to 1606 when it opens the project, so a
    // `file.reload/v1` against a file still saying 1600 is refused as a downgrade. Whoever is
    // about to use the fast path needs the number; nobody needs a warning about it.
    if (p.model.compatibilityLevel !== null) {
      p.checked.push(
        `model compatibilityLevel: ${p.model.compatibilityLevel}`
        + (p.model.compatibilityLevel < 1606
            ? " (Desktop raises this to 1606 in memory on open, so reload is refused as a "
              + "downgrade until database.tmdl says 1606 — this is not a fault in the model)"
            : ""));
    }


    // Same shape as compatibilityLevel above, same reason: a FACT the caller needs at the moment
    // it reloads, not a defect. A `cultures/` file makes `file.reload/v1` die while the project
    // cold-opens perfectly, so the symptom is "the fast loop stopped working" with nothing on
    // screen naming the cause. It cost seven cold opens on 2026-08-15 before anyone connected the
    // two. Not a finding: the file is legitimate and Desktop is happy with it.
    if (p.model.cultureFiles && p.model.cultureFiles.length) {
      p.checked.push(
        `${p.model.cultureFiles.length} cultures/ file(s) — file.reload/v1 will not work on this `
        + `project (it cold-opens normally). Budget a cold open per iteration, or remove the `
        + `cultures file if nothing needs it.`);
    }
    const sc = tmdl.scenarioMeasures(p.model);
    const dt = tmdl.dateTable(p.model);

    // Not rules from the held catalogue. These are project-shape facts, the same class as
    // unparseable-json above, and nothing else in the plugin can see them.
    //
    // NARROWED 2026-08-15. `scenarioMeasures` recognises a scenario by NAME (ac/actual, pl/plan/
    // budget, py/previous year, fc/forecast) plus a base-measure test. That is a naming convention,
    // and a legitimate report can carry none of those names: the documented fallback for a dataset
    // with no scenario column and no date column is BENCHMARK-VS-POPULATION -- bind the sliced
    // measure to `Values` and an ALL() population measure to `Plan`, and the variance column reads
    // "how far this band sits from everyone". Measures called `Avg Score` and `Population Avg` are
    // exactly that, and the rule fired on a report that WAS a working variance report.
    //
    // So look at the report before claiming a variance is impossible: if any visual actually binds
    // a comparison well, the premise is refuted by the file in front of us. This can only ever
    // SUPPRESS a finding, never add one, so it cannot introduce a false positive of its own.
    const bindsAComparison = [...p.files.values()].some((f) => {
      const qs = f.parsed?.visual?.query?.queryState;
      if (!qs) return false;
      return ["Plan", "PreviousYear", "Forecast"].some(
        (role) => (qs[role]?.projections || []).length > 0);
    });
    if ((!sc.hasActual || !sc.hasComparative) && !bindsAComparison) {
      p.problems.push({
        code: "model-has-no-scenario-measures", severity: "wrong-numbers",
        location: p.model.files[0] || "the semantic model",
        message: "This model has no per-scenario measures, so a variance report is not possible: "
          + "`Values` and `Plan` are separate wells and need separate fields. Every variance and "
          + "prior-year column will be empty or meaningless while the page still looks finished. "
          + "Add measures per scenario, for example AC, PL and PY.",
      });
    }
    // Only a model that computes prior year with time intelligence can suffer the fault this rule
    // describes. See the note in tmdl.dateTable -- 8 of 20 shipped templates fired, and at least two
    // of them use no time-intelligence function at all.
    // REWORDED 2026-08-05, and demoted from `wrong-numbers`. The old message ended "prior year
    // equals actual, the delta reads a flat 0.0%, and nothing on screen says so" -- a real,
    // measured symptom BORROWED FROM A DIFFERENT FAULT. The skill and the held catalogue both attribute
    // PY ≡ AC to no time context in the visual's grouping or filter, not to an unmarked table.
    // Marking is genuinely best practice, and DATEADD or SAMEPERIODLASTYEAR against a contiguous
    // date column still computes without it -- which is what the four remaining shipped templates
    // do, correctly. So this is a risk note, not a detected defect, and it says so.
    if (!dt.marked && dt.usesTimeIntelligence) {
      p.problems.push({
        code: "no-date-table-marked", severity: "looks-fine",
        location: dt.candidate ? `${dt.candidate} (not marked)` : "the semantic model",
        message: "This model computes prior year or year-to-date, but no table is marked as the "
          + "date table — `dataCategory: Time` plus a key column. Time intelligence against a "
          + "contiguous date column still computes without it, so this is not proof of a wrong "
          + "number. It does leave Power BI free to build its own auto date/time hierarchy "
          + "alongside yours, and a visual that groups on the wrong one of the two is wrong "
          + "while looking right. Mark it."
          + (dt.candidate ? ` \`${dt.candidate}\` looks like the intended calendar.` : ""),
      });
    }
  }

  return p;
}

// --- the tool -----------------------------------------------------------------------------

/**
 * The mechanical half of planning. Resolves the project, then enumerates it.
 *
 * Deliberately shares `resolveProject` with `validate_report`: an enumeration computed from a
 * different read of the project than the validator uses is an enumeration that can disagree with
 * it, and two instruments disagreeing silently is this project's most expensive failure class.
 */
function profileProjectTool(args) {
  const projectPath = args && args.projectPath;
  if (typeof projectPath !== "string" || !projectPath) {
    return { ok: false, error: "projectPath is required and must be a string" };
  }
  const p = resolveProject(projectPath);
  if (!p || p.fatal) {
    return { ok: false, error: (p && p.fatal) || "the project could not be read" };
  }
  return prof.profileProject(p);
}

function validateReport(args) {
  const projectPath = args && args.projectPath;
  const rules = loadRules();

  if (rules === null) {
    return {
      ok: false,
      error:
        "The rule catalogue is missing or unreadable, so nothing was checked. This is a broken " +
        "install rather than a clean report. Reinstall the plugin.",
    };
  }

  const project = resolveProject(projectPath);
  if (project.fatal) return { ok: false, error: project.fatal };

  const findings = [...project.problems];
  const ran = [];
  const carriedNotRun = [];

  for (const rule of rules) {
    const fn = checkers[rule.check];
    if (!fn) { carriedNotRun.push(rule.id); continue; }
    ran.push(rule.id);
    for (const hit of fn(project)) {
      findings.push({
        code: rule.id,
        severity: rule.severity,
        location: hit.location,
        message: rule.message,
        // The per-hit detail, which was computed and then dropped here. Two checkers set it and
        // both lose their point without it: `data-role-exceeds-declared-maximum` produces
        // "3 of max 1", and the calculated-table relationship rule produces the one sentence that
        // sends the reader to the column rather than the relationship. Corrected 2026-08-31.
        ...(hit.detail ? { detail: hit.detail } : {}),
      });
    }
  }

  const severityOrder = { "wont-open": 0, blank: 1, "wrong-numbers": 2, "looks-fine": 3 };
  findings.sort((a, b) => (severityOrder[a.severity] ?? 9) - (severityOrder[b.severity] ?? 9));

  return {
    ok: true,
    findings,
    checked: project.checked,
    rulesRun: ran.length,
    // Never empty, and deliberately specific. A green result from this tool is not a claim
    // that the report is correct, and the two largest classes of Zebra defect live here.
    notChecked: [
      "Whether any number is right. Nothing here reads your data.",
      "Whether the actuals cover the same window as the comparison. A partial trailing " +
        "month produces a confident, completely wrong variance, and no file check can see it.",
      "Whether the report renders. Only a screenshot shows that.",
      ...(project.notCheckedExtra ?? []),
      ...(carriedNotRun.length
        ? [`${carriedNotRun.length} rule(s) are in the catalogue but have no checker yet.`]
        : []),
    ],
  };
}

